// Loops are used for repeating actions

void main() {
  for (int i = 1; i <= 5; i++){
    print("Assalam-o-Alykum Mr. Bilred! $i");
  }
}

// Initialization (int i = 1): Start the counter at 1.
// Condition (i <= 5): Loop runs while i is 5 or less.
// Increment (i++): Increase i by 1 each time the loop runs.